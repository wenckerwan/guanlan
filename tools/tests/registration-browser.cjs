// Production browser acceptance. Use an authorized disposable mailbox alias; send and complete are separate phases.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'D:/code_files/考研政治工程文件/近现代史时间轴/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const base = 'https://guanlan.wencker.top';
const [phase, email, label, code] = process.argv.slice(2);
const out = path.resolve(__dirname, '../../output/registration-qa');
fs.mkdirSync(out, { recursive: true });
const json = value => console.log(JSON.stringify(value));

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(30000);
  const password = 'Qa!' + crypto.randomBytes(18).toString('hex');
  try {
    if (phase === 'send') {
      await page.goto(base + '/login?mode=register');
      await page.getByRole('heading', { name: '创建观澜账号' }).waitFor();
      await page.getByLabel('昵称（可选）').fill(label);
      await page.getByLabel('邮箱', { exact: true }).fill(email);
      await page.getByLabel('密码', { exact: true }).fill(password);
      assert.equal(await page.locator('input[autocomplete="one-time-code"]').getAttribute('required'), '');
      assert.equal(await page.locator('.auth-form').evaluate(form => form.checkValidity()), false);
      const short = await context.request.post(base + '/api/v1/auth/register', { data: { email, password: '123', displayName: label } });
      assert.equal(short.status(), 422);
      const missing = await context.request.post(base + '/api/v1/auth/register', { data: { email, password, displayName: label } });
      assert.equal(missing.status(), 409);
      assert.match((await missing.json()).message, /验证码/);
      json({ phase: 'validation', missingCodeBlocked: true, shortPasswordBlocked: true });
      const response = page.waitForResponse(r => r.url().endsWith('/auth/email/code') && r.request().method() === 'POST', { timeout: 90000 });
      const started = Date.now();
      await page.getByRole('button', { name: '获取验证码', exact: true }).click();
      const sent = await response;
      const body = await sent.json();
      await page.screenshot({ path: path.join(out, 'send.png') });
      json({ phase: 'send', status: sent.status(), elapsedMs: Date.now() - started, response: body });
      assert.equal(sent.status(), 200);
      assert.match(await page.locator('.auth-notice').innerText(), /验证码已发送/);
      const retry = await context.request.post(base + '/api/v1/auth/email/code', { data: { email } });
      assert.equal(retry.status(), 429);
      json({ phase: 'send-verified', repeatSendLimited: true, pageErrors: errors });
      assert.deepEqual(errors, []);
    } else if (phase === 'complete') {
      assert.match(code, /^\d{6}$/);
      await page.goto(base + '/login?mode=register');
      await page.getByRole('heading', { name: '创建观澜账号' }).waitFor();
      await page.getByLabel('昵称（可选）').fill(label);
      await page.getByLabel('邮箱', { exact: true }).fill(email);
      await page.getByLabel('密码', { exact: true }).fill(password);
      const wrong = String((Number(code) + 1) % 1000000).padStart(6, '0');
      await page.locator('input[autocomplete="one-time-code"]').fill(wrong);
      let response = page.waitForResponse(r => r.url().endsWith('/auth/register') && r.request().method() === 'POST');
      await page.getByRole('button', { name: '注册并登录', exact: true }).click();
      assert.equal((await response).status(), 409);
      await page.locator('.auth-error').filter({ hasText: '验证码不正确' }).waitFor();
      await page.locator('input[autocomplete="one-time-code"]').fill(code);
      response = page.waitForResponse(r => r.url().endsWith('/auth/register') && r.request().method() === 'POST');
      await page.getByRole('button', { name: '注册并登录', exact: true }).click();
      const registered = await response;
      assert.equal(registered.status(), 201);
      const payload = (await registered.json()).data;
      const account = { userId: payload.user.id, email, displayName: payload.user.displayName, mistakeCode: payload.user.mistakeCode };
      fs.writeFileSync(path.join(out, 'created-account.json'), JSON.stringify(account, null, 2));
      assert.equal(payload.user.email, email);
      assert.equal(payload.user.role, 'user');
      assert.ok(payload.user.mistakeCode);
      const token = payload.token;
      await page.waitForURL('**/me');
      await page.getByRole('heading', { name: label, exact: true }).waitFor();
      await page.screenshot({ path: path.join(out, 'registered.png') });
      await page.reload();
      await page.getByRole('heading', { name: label, exact: true }).waitFor();
      const me = await context.request.get(base + '/api/v1/auth/me', { headers: { Authorization: 'Bearer ' + token } });
      assert.equal(me.status(), 200);
      const duplicate = await context.request.post(base + '/api/v1/auth/register', { data: { email, password, displayName: label, code } });
      assert.equal(duplicate.status(), 409);
      await page.getByRole('button', { name: '退出', exact: true }).click();
      await page.getByRole('link', { name: '登录', exact: true }).first().waitFor();
      const revoked = await context.request.get(base + '/api/v1/auth/me', { headers: { Authorization: 'Bearer ' + token } });
      assert.equal(revoked.status(), 401);
      await page.goto(base + '/login');
      await page.getByLabel('邮箱', { exact: true }).fill(email);
      await page.getByLabel('密码', { exact: true }).fill('wrong-password-for-qa');
      response = page.waitForResponse(r => r.url().endsWith('/auth/login') && r.request().method() === 'POST');
      await page.locator('.auth-form').getByRole('button', { name: '登录', exact: true }).click();
      assert.equal((await response).status(), 401);
      await page.getByLabel('密码', { exact: true }).fill(password);
      response = page.waitForResponse(r => r.url().endsWith('/auth/login') && r.request().method() === 'POST');
      await page.locator('.auth-form').getByRole('button', { name: '登录', exact: true }).click();
      assert.equal((await response).status(), 200);
      await page.waitForURL('**/me');
      await page.getByRole('heading', { name: label, exact: true }).waitFor();
      await page.setViewportSize({ width: 390, height: 844 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      await page.screenshot({ path: path.join(out, 'mobile-account.png') });
      assert.deepEqual(errors, []);
      json({ phase: 'complete', ...account, registrationStatus: 201, wrongCodeRejected: true, autoLogin: true, refreshRestored: true, duplicateBlocked: true, logoutTokenRevoked: true, wrongPasswordRejected: true, loginAgain: true, mobileOverflow: false, pageErrors: errors });
    } else throw Error('Unknown phase');
  } catch (error) {
    await page.screenshot({ path: path.join(out, 'failure-' + phase + '.png') }).catch(() => {});
    json({ phase: 'failure', message: error.message, pageErrors: errors });
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error.message); process.exit(1); });
